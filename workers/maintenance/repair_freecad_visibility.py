from __future__ import annotations

import argparse
import os
from pathlib import Path

import FreeCAD as App


DEFAULT_GENERATED_MODELS = Path(
    os.getenv("STUDIO_GENERATED_MODEL_DIR", Path.cwd() / "workers" / "generated_models")
)
FALLBACK_GENERATED_MODELS = Path(r"D:\Winnsen_Structure_Agent_Studio\workers\generated_models")

MACRO_TEXT = """import FreeCAD as App
import FreeCADGui as Gui

doc = App.ActiveDocument
if doc is not None:
    for obj in doc.Objects:
        try:
            obj.Visibility = True
        except Exception:
            pass
        view = getattr(obj, 'ViewObject', None)
        if view is not None:
            try:
                view.Visibility = True
            except Exception:
                pass
    doc.recompute()
    try:
        Gui.SendMsgToActiveView('ViewFit')
    except Exception:
        pass
"""

NOTES_TEXT = """# FreeCAD opening notes

- `.FCStd` is the native FreeCAD engineering-reference model.
- The file is generated by `FreeCADCmd`, so it may not contain a saved GUI camera/view state.
- If the 3D view looks blank after opening, use `View > Fit all` or run `show_all_objects_and_fit_view.FCMacro` in FreeCAD.
- The companion `.step/.stp` file is the neutral geometry handoff and can also be opened directly in FreeCAD or SolidWorks.
"""


def fcstd_paths(root: Path) -> list[Path]:
    if root.is_file() and root.suffix.lower() == ".fcstd":
        return [root]
    return sorted(root.rglob("*.FCStd"))


def write_opening_helpers(directory: Path) -> None:
    (directory / "show_all_objects_and_fit_view.FCMacro").write_text(MACRO_TEXT, encoding="utf-8")
    (directory / "freecad_opening_notes.md").write_text(NOTES_TEXT, encoding="utf-8")


def repair_file(path: Path) -> tuple[int, int]:
    doc = App.openDocument(str(path))
    repaired = 0
    total = 0
    try:
        total = len(doc.Objects)
        for obj in doc.Objects:
            if hasattr(obj, "Visibility") and not obj.Visibility:
                obj.Visibility = True
                repaired += 1
        doc.recompute()
        doc.save()
    finally:
        App.closeDocument(doc.Name)
    write_opening_helpers(path.parent)
    return total, repaired


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("paths", nargs="*", help="FCStd files or directories to repair.")
    args = parser.parse_args()

    targets: list[Path] = []
    default_paths = [str(DEFAULT_GENERATED_MODELS), str(FALLBACK_GENERATED_MODELS)]
    for value in args.paths or default_paths:
        targets.extend(fcstd_paths(Path(value)))
    if not targets and args.paths:
        for value in default_paths:
            targets.extend(fcstd_paths(Path(value)))
    unique_targets: list[Path] = []
    seen: set[str] = set()
    for target in targets:
        key = str(target.resolve()).lower()
        if key not in seen:
            seen.add(key)
            unique_targets.append(target)
    targets = unique_targets

    if not targets:
        print("No FCStd files found.")
        return

    for path in targets:
        total, repaired = repair_file(path)
        print(f"{path} objects={total} repaired_visibility={repaired}")


main()
